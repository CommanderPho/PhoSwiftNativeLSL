#!/usr/bin/env bash
set -euo pipefail
IFS=$'\n\t'

# --- Config (edit only if needed) ---
LSL_REPO="https://github.com/sccn/liblsl.git"
WORKDIR="$(pwd)/liblsl-tuist-workspace"
CLONE_DIR="$WORKDIR/third_party/liblsl"
BUILD_DIR_BASE="$WORKDIR/build"
ARCHIVE_DIR="$WORKDIR/archives"
FRAMEWORKS_DIR="$WORKDIR/Frameworks"
XCFRAMEWORK_NAME="liblsl.xcframework"
LSL_TARGET="${LSL_TARGET:-lsl}" # override if upstream CMake target/scheme differs
TUIST_PROJECT_NAME="LSLExampleWorkspace"
TUIST_MIN_VERSION="3.4.0" # optional constraint for tuist generation
# --- end config ---

mkdir -p "$WORKDIR" "$ARCHIVE_DIR" "$FRAMEWORKS_DIR"
echo "Workspace: $WORKDIR"

# Check prerequisites
for cmd in git cmake xcodebuild xcode-select; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Missing required tool: $cmd. Install Xcode (and command line tools) and re-run." >&2
    exit 1
  fi
done

if ! command -v tuist >/dev/null 2>&1; then
  echo "Tuist not found. Installing tuist (system-wide)..." >&2
  curl -Ls https://install.tuist.io | bash || true
  if ! command -v tuist >/dev/null 2>&1; then
    echo "tuist install failed or requires interactive step; please install tuist (https://tuist.io) and re-run." >&2
    exit 1
  fi
fi

# Clone liblsl
rm -rf "$CLONE_DIR"
git clone --depth 1 "$LSL_REPO" "$CLONE_DIR"
cd "$CLONE_DIR"

# Detect project name (for Xcode project generated by cmake)
PROJECT_NAME="$(basename "$CLONE_DIR")"

# Helper: wipe a CMake build dir if its cache was generated for a different path
# (common after relocating the repo, e.g. /Users/... -> /Volumes/...)
invalidate_stale_cmake_cache() {
  local builddir="$1"
  local cache="$builddir/CMakeCache.txt"
  [ -f "$cache" ] || return 0

  local cached_home cached_dir
  cached_home=$(grep -E '^CMAKE_HOME_DIRECTORY:INTERNAL=' "$cache" 2>/dev/null | cut -d= -f2- || true)
  cached_dir=$(grep -E '^CMAKE_CACHEFILE_DIR:INTERNAL=' "$cache" 2>/dev/null | cut -d= -f2- || true)

  if { [ -n "$cached_home" ] && [ "$cached_home" != "$CLONE_DIR" ]; } || \
     { [ -n "$cached_dir" ] && [ "$cached_dir" != "$builddir" ]; }; then
    echo "Stale CMake cache in $builddir (was generated under a different path); cleaning..." >&2
    rm -rf "$builddir"
  fi
}

# Helper: run cmake configure for a build dir (Xcode generator)
cmake_configure() {
  local builddir="$1"
  invalidate_stale_cmake_cache "$builddir"
  mkdir -p "$builddir"
  pushd "$builddir" >/dev/null
  
  # Determine SDK and architecture based on build directory name
  local sdk=""
  local arch=""
  if [[ "$builddir" == *"iphoneos"* ]]; then
    sdk="iphoneos"
    arch="arm64"
  elif [[ "$builddir" == *"iphonesimulator"* ]]; then
    sdk="iphonesimulator"
    # Simulator can be x86_64 or arm64 depending on host
    arch="arm64;x86_64"
  elif [[ "$builddir" == *"watchos"* ]]; then
    sdk="watchos"
    arch="arm64"
  elif [[ "$builddir" == *"watchsimulator"* ]]; then
    sdk="watchsimulator"
    arch="arm64;x86_64"
  elif [[ "$builddir" == *"macosx"* ]]; then
    sdk="macosx"
    # macOS can be both arm64 and x86_64
    arch="arm64;x86_64"
  fi
  
  # Get the SDK path
  local sdk_path=""
  if [ -n "$sdk" ]; then
    sdk_path=$(xcrun --sdk "$sdk" --show-sdk-path 2>/dev/null || true)
  fi
  
  # Build cmake command
  local cmake_args=(-G Xcode "$CLONE_DIR" -DCMAKE_BUILD_TYPE=Release -DLSL_BUILD_STATIC=ON)
  
  if [ -n "$sdk" ] && [ -n "$sdk_path" ]; then
    cmake_args+=(-DCMAKE_OSX_SYSROOT="$sdk_path")
    echo "Configuring for SDK: $sdk with path: $sdk_path" >&2
  fi
  
  if [ -n "$arch" ]; then
    cmake_args+=(-DCMAKE_OSX_ARCHITECTURES="$arch")
    echo "Setting architectures: $arch" >&2
  fi
  
  cmake "${cmake_args[@]}"
  popd >/dev/null
}

# Common xcodebuild flags: LLVM LTO leaves bitcode objects in .a/.framework
# binaries that xcodebuild -create-xcframework cannot consume.
XCODE_DIST_FLAGS=(
  SKIP_INSTALL=NO
  BUILD_LIBRARY_FOR_DISTRIBUTION=YES
  LLVM_LTO=NO
  ENABLE_BITCODE=NO
  BITCODE_GENERATION_MODE=none
)

# Helper: archive for given sdk (macosx / iphoneos / iphonesimulator / watchos / watchsimulator)
archive_for_sdk() {
  local builddir="$1"
  local sdk="$2"
  local archname="$3"   # label for archives
  pushd "$builddir" >/dev/null
  # find the Xcode project generated by cmake
  proj=$(find . -maxdepth 2 -name '*.xcodeproj' | head -n1)
  if [ -z "$proj" ]; then
    echo "Error: Xcode project not found in $builddir" >&2
    exit 1
  fi
  proj_path="$builddir/$proj"
  archive_path="$ARCHIVE_DIR/$archname.xcarchive"
  mkdir -p "$(dirname "$archive_path")"
  # Try archive. If scheme not found, try auto-discovering available schemes.
  set +e
  selected_scheme="$LSL_TARGET"
  xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release -sdk "$sdk" archive -archivePath "$archive_path" "${XCODE_DIST_FLAGS[@]}" >/dev/null 2>&1
  rc=$?
  set -e
  if [ $rc -ne 0 ]; then
    echo "xcodebuild archive with scheme $LSL_TARGET failed for sdk $sdk; discovering available schemes..." >&2
    set +e
    mapfile -t schemes < <(xcodebuild -list -project "$proj_path" 2>/dev/null | awk '/Schemes:/{flag=1;next}/Targets:/{flag=0}flag' | sed 's/^ *//;s/ *$//' | sed '/^$/d')
    set -e
    tried_ok=0
    for sch in "${schemes[@]}"; do
      echo "Trying scheme '$sch' for sdk $sdk..." >&2
      set +e
      xcodebuild -project "$proj_path" -scheme "$sch" -configuration Release -sdk "$sdk" archive -archivePath "$archive_path" "${XCODE_DIST_FLAGS[@]}" >/dev/null 2>&1
      rc2=$?
      set -e
      if [ $rc2 -eq 0 ]; then
        echo "Archived with scheme '$sch' for $sdk." >&2
        tried_ok=1
        selected_scheme="$sch"
        break
      fi
    done
    if [ "$tried_ok" -ne 1 ]; then
      echo "Failed to archive any scheme for sdk $sdk. Available schemes: ${schemes[*]}" >&2
      echo "Falling back to building the selected scheme to collect libraries." >&2
    fi
  fi
  # If archive exists but is empty (no libs/frameworks), treat as missing
  need_build_fallback=0
  if [ -d "$archive_path" ]; then
    set +e
    find "$archive_path" \( -name 'lib*.a' -o -name 'lib*.dylib' -o -path '*/Products/Library/Frameworks/*.framework' \) -print -quit | grep -q .
    has_artifacts=$?
    set -e
    if [ $has_artifacts -ne 0 ]; then
      echo "Archive at $archive_path contains no libraries/frameworks; falling back to build products." >&2
      need_build_fallback=1
    fi
  else
    need_build_fallback=1
  fi

  if [ $need_build_fallback -eq 1 ]; then
    echo "Performing build for $selected_scheme ($sdk) and using build products." >&2
    
    # Handle iOS simulator: build for both arm64 and x86_64, then create universal binary
    if [ "$sdk" = "iphonesimulator" ]; then
      # Try to build for both architectures (x86_64 for Intel, arm64 for Apple Silicon)
      archs=("x86_64" "arm64")
      lib_paths=()
      
      # Build for each architecture
      for arch in "${archs[@]}"; do
        echo "Building for architecture: $arch" >&2
        set +e
        xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release \
          -sdk "$sdk" -arch "$arch" ONLY_ACTIVE_ARCH=YES \
          "${XCODE_DIST_FLAGS[@]}" \
          CONFIGURATION_BUILD_DIR="$builddir/Release-$arch" >/dev/null 2>&1
        build_rc=$?
        set -e
        
        if [ $build_rc -eq 0 ]; then
          # Prefer lsl.framework (modern liblsl), then liblsl.a / dylib
          fw=$(find "$builddir/Release-$arch" -type d -name "lsl.framework" 2>/dev/null | head -n1 || true)
          if [ -n "$fw" ] && [ -d "$fw" ]; then
            lib_paths+=("$fw/lsl")
            echo "Found framework binary for $arch: $fw/lsl" >&2
          else
            lib=$(find "$builddir/Release-$arch" -type f \( -name "liblsl.a" -o -name "liblsl*.dylib" \) ! -name "liblslobj*" 2>/dev/null | head -n1 || true)
            if [ -n "$lib" ] && [ -f "$lib" ]; then
              lib_paths+=("$lib")
              echo "Found library for $arch: $lib" >&2
            else
              echo "Warning: Library not found for $arch after build" >&2
            fi
          fi
        else
          echo "Build for $arch failed (may not be supported on this host)" >&2
        fi
      done
      
      # Create universal binary if we have multiple architectures
      if [ ${#lib_paths[@]} -gt 1 ]; then
        echo "Creating universal binary from ${lib_paths[*]}" >&2
        base_lib="${lib_paths[0]}"
        if [[ "$base_lib" == */lsl.framework/lsl ]]; then
          mkdir -p "$builddir/Release"
          cp -R "$(dirname "$base_lib")" "$builddir/Release/lsl.framework"
          lipo -create "${lib_paths[@]}" -output "$builddir/Release/lsl.framework/lsl" || {
            echo "lipo failed, using first architecture framework binary" >&2
            cp "${lib_paths[0]}" "$builddir/Release/lsl.framework/lsl"
          }
        else
          if [[ "$base_lib" == *.dylib ]]; then
            lib_name="liblsl.dylib"
          else
            lib_name="liblsl.a"
          fi
          universal_lib="$builddir/Release/$lib_name"
          mkdir -p "$builddir/Release"
          lipo -create "${lib_paths[@]}" -output "$universal_lib" || {
            echo "lipo failed, using first architecture library" >&2
            cp "${lib_paths[0]}" "$universal_lib"
          }
        fi
        echo "$builddir/Release"
      elif [ ${#lib_paths[@]} -eq 1 ]; then
        echo "Using single architecture library" >&2
        mkdir -p "$builddir/Release"
        if [[ "${lib_paths[0]}" == */lsl.framework/lsl ]]; then
          cp -R "$(dirname "${lib_paths[0]}")" "$builddir/Release/lsl.framework"
        else
          cp "${lib_paths[0]}" "$builddir/Release/"
        fi
        echo "$builddir/Release"
      else
        echo "Error: No libraries built for iphonesimulator" >&2
        exit 1
      fi
      popd >/dev/null
      return 0
    fi
    
    # For iphoneos, explicitly build for arm64
    if [ "$sdk" = "iphoneos" ]; then
      echo "Building for architecture: arm64 (device)" >&2
      set +e
      xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release \
        -sdk "$sdk" -arch arm64 ONLY_ACTIVE_ARCH=YES \
        "${XCODE_DIST_FLAGS[@]}" \
        CONFIGURATION_BUILD_DIR="$builddir/Release-iphoneos-arm64" 2>&1 | grep -v "note:" | grep -v "warning:" || true
      set -e
      
      # Prefer framework product, then static/dylib
      fw_path=$(find "$builddir/Release-iphoneos-arm64" -type d -name "lsl.framework" 2>/dev/null | head -n1 || true)
      lib_path=""
      if [ -n "$fw_path" ] && [ -d "$fw_path" ]; then
        echo "Found iOS device framework: $fw_path" >&2
        echo "$(dirname "$fw_path")"
        popd >/dev/null
        return 0
      fi

      lib_path=$(find "$builddir/Release-iphoneos-arm64" -type f \( -name "liblsl.a" -o -name "liblsl*.dylib" \) ! -name "liblslobj*" 2>/dev/null | head -n1 || true)
      
      # If not found, search more broadly
      if [ -z "$lib_path" ] || [ ! -f "$lib_path" ]; then
        lib_path=$(find "$builddir" -type f \( -name "liblsl.a" -o -name "liblsl*.dylib" \) ! -name "liblslobj*" \
          \( -path "*/Release/*" -o -path "*/Release-*/*" -o -path "*/Release" \) 2>/dev/null | head -n1 || true)
      fi
      
      # Verify the library has arm64 architecture for device
      if [ -n "$lib_path" ] && [ -f "$lib_path" ]; then
        archs=$(lipo -info "$lib_path" 2>/dev/null | grep -o "arm64" || true)
        if [ -z "$archs" ]; then
          echo "Warning: Library at $lib_path does not contain arm64 architecture" >&2
        else
          echo "Verified: Library contains arm64 architecture" >&2
        fi
        output_dir=$(dirname "$lib_path")
        echo "$output_dir"
      else
        echo "Error: Could not find iOS device library after build" >&2
        echo "$builddir/Release"
      fi
    else
      # For other SDKs, use default build
      xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release \
        -sdk "$sdk" build "${XCODE_DIST_FLAGS[@]}" >/dev/null 2>&1
      
      fw_path=$(find "$builddir" -type d -name "lsl.framework" \
        \( -path "*/Release/*" -o -path "*/Release-*/*" \) 2>/dev/null | head -n1 || true)
      if [ -n "$fw_path" ] && [ -d "$fw_path" ]; then
        echo "$(dirname "$fw_path")"
        popd >/dev/null
        return 0
      fi

      # Discover actual build output location (can vary by SDK)
      lib_path=$(find "$builddir" -type f \( -name "liblsl.a" -o -name "liblsl*.dylib" \) ! -name "liblslobj*" \
        \( -path "*/Release/*" -o -path "*/Release-*/*" -o -path "*/Release" \) 2>/dev/null | head -n1 || true)
      
      if [ -n "$lib_path" ] && [ -f "$lib_path" ]; then
        output_dir=$(dirname "$lib_path")
        echo "$output_dir"
      else
        # Fallback to standard Release directory (may need to check if build actually succeeded)
        echo "$builddir/Release"
      fi
    fi
    popd >/dev/null
    return 0
  fi
  popd >/dev/null
  echo "$archive_path"
}

# Platforms list to attempt (order: device then simulator)
declare -a SDKS=( "macosx" "iphoneos" "iphonesimulator" "watchos" "watchsimulator" )

# Configure and archive per SDK
declare -a BUILD_OUTPUTS=()
declare -A SDK_TO_OUTPUT=()
for sdk in "${SDKS[@]}"; do
  bd="$BUILD_DIR_BASE/$sdk"
  echo "Configuring CMake for $sdk -> $bd"
  cmake_configure "$bd"
  echo "Archiving for sdk $sdk"
  output=$(archive_for_sdk "$bd" "$sdk" "$sdk")
  if [ -n "$output" ] && [ -d "$output" ]; then
    BUILD_OUTPUTS+=("$output")
    SDK_TO_OUTPUT["$sdk"]="$output"
  fi
done

# Collect framework/library + headers from build outputs (archives or build directories)
found_frameworks=()
found_libraries=()
found_headers=()

# Track which SDK each library belongs to
declare -A LIB_TO_SDK=()

# Use include directory from source for headers (consistent across all builds)
headers_dir="$CLONE_DIR/include"
if [ -d "$headers_dir" ]; then
  found_headers+=("$headers_dir")
fi

# Process each SDK's output
for sdk in "${SDKS[@]}"; do
  output="${SDK_TO_OUTPUT[$sdk]}"
  if [ -z "$output" ] || [ ! -d "$output" ]; then
    echo "Skipping $sdk - no output directory found" >&2
    continue
  fi
  
  echo "Processing output for $sdk: $output" >&2
  lib=""
  
  # Check if this is an archive (has Products directory) or a build directory
  if [ -d "$output/Products" ]; then
    # This is an xcarchive - look for frameworks in Products
    fw=$(find "$output" -path "*/Products/Library/Frameworks/*.framework" | head -n1 || true)
    if [ -n "$fw" ] && [ -d "$fw" ]; then
      echo "Found framework for $sdk: $fw"
      found_frameworks+=("$fw")
      continue
    fi
    # Look for libraries in archive Products
    lib=$(find "$output/Products" -name "liblsl*.dylib" ! -name "liblslobj*" | head -n1 || true)
    if [ -z "$lib" ]; then
      lib=$(find "$output/Products" -name "liblsl.a" | head -n1 || true)
    fi
  else
    # Prefer modern lsl.framework product from liblsl CMake
    fw=$(find "$output" -maxdepth 2 -type d -name "lsl.framework" 2>/dev/null | head -n1 || true)
    if [ -n "$fw" ] && [ -d "$fw" ]; then
      echo "Found framework for $sdk: $fw"
      found_frameworks+=("$fw")
      continue
    fi

    # This is a build directory - look for libraries more thoroughly
    lib=$(find "$output" -maxdepth 2 -type f \( -name "liblsl.a" -o -name "liblsl*.dylib" \) ! -name "liblslobj*" | head -n1 || true)
    
    # For iphoneos, specifically look for arm64 builds
    if [ "$sdk" = "iphoneos" ] && ([ -z "$lib" ] || [ ! -f "$lib" ]); then
      lib=$(find "$output" -type f \( -name "liblsl.a" -o -name "liblsl*.dylib" \) ! -name "liblslobj*" -exec sh -c 'lipo -info "$1" 2>/dev/null | grep -q arm64 && echo "$1"' _ {} \; | head -n1 || true)
    fi
  fi
  
  if [ -n "$lib" ] && [ -f "$lib" ]; then
    echo "Found library for $sdk: $lib"
    found_libraries+=("$lib")
    LIB_TO_SDK["$lib"]="$sdk"
    
    # Verify architecture matches expected SDK
    if [ "$sdk" = "iphoneos" ]; then
      archs=$(lipo -info "$lib" 2>/dev/null | grep -o "arm64" || true)
      if [ -z "$archs" ]; then
        echo "Warning: iOS device library should contain arm64, but found: $(lipo -info "$lib" 2>&1)" >&2
      fi
    fi
  else
    echo "Warning: No library found for $sdk in $output" >&2
  fi
done

XC_OUT="$FRAMEWORKS_DIR/$XCFRAMEWORK_NAME"
rm -rf "$XC_OUT"
echo "Creating XCFramework at $XC_OUT"

# Prefer framework -> create xcframework from frameworks
if [ ${#found_frameworks[@]} -gt 0 ]; then
  # Build xcodebuild -create-xcframework with all frameworks
  create_cmd=(xcodebuild -create-xcframework)
  for fw in "${found_frameworks[@]}"; do
    create_cmd+=(-framework "$fw")
  done
  create_cmd+=(-output "$XC_OUT")
  "${create_cmd[@]}"
else
  # Create xcframework from static/dylib + headers (use -library + -headers for each slice)
  if [ ${#found_libraries[@]} -eq 0 ]; then
    echo "No frameworks or libraries found in build outputs; aborting." >&2
    exit 1
  fi
  create_cmd=(xcodebuild -create-xcframework)
  # Use the shared headers directory for all libraries (from source)
  hdrdir="${found_headers[0]:-$CLONE_DIR/include}"
  if [ ! -d "$hdrdir" ]; then
    echo "Warning: Headers directory not found at $hdrdir, libraries may be incomplete" >&2
  fi
  
  # Verify we have at least the iOS device library
  iphoneos_lib_found=0
  for lib in "${found_libraries[@]}"; do
    if [ "${LIB_TO_SDK[$lib]}" = "iphoneos" ]; then
      iphoneos_lib_found=1
      echo "iOS device (arm64) library found: $lib"
      # Double-check it has arm64
      archs=$(lipo -info "$lib" 2>/dev/null || echo "")
      if echo "$archs" | grep -q "arm64"; then
        echo "Confirmed: Library contains arm64 architecture"
      else
        echo "Warning: iOS device library may not have correct architecture: $archs" >&2
      fi
      break
    fi
  done
  
  if [ $iphoneos_lib_found -eq 0 ]; then
    echo "Error: iOS device (iphoneos/arm64) library not found. Cannot create xcframework with device support." >&2
    echo "Found libraries:" >&2
    for lib in "${found_libraries[@]}"; do
      echo "  - ${LIB_TO_SDK[$lib]}: $lib" >&2
    done
    exit 1
  fi
  
  echo "Creating xcframework with ${#found_libraries[@]} library slices:"
  for lib in "${found_libraries[@]}"; do
    sdk="${LIB_TO_SDK[$lib]}"
    echo "  - Adding $sdk: $lib"
    create_cmd+=(-library "$lib" -headers "$hdrdir")
  done
  create_cmd+=(-output "$XC_OUT")
  
  echo "Running: ${create_cmd[*]}" >&2
  "${create_cmd[@]}"
fi

echo "XCFramework created: $XC_OUT"

# Verify the xcframework contains iOS device support
if [ -f "$XC_OUT/Info.plist" ]; then
  if grep -q "ios-arm64" "$XC_OUT/Info.plist" 2>/dev/null || \
     [ -d "$XC_OUT/ios-arm64" ]; then
    echo "Success: XCFramework contains iOS device (arm64) support"
  else
    echo "Warning: XCFramework may not contain iOS device support. Checking structure..." >&2
    ls -la "$XC_OUT/" >&2
  fi
else
  echo "Warning: Could not verify xcframework structure - Info.plist not found" >&2
fi

# Also install into the Tuist project Frameworks/ if it already exists from a prior run
if [ -d "$WORKDIR/LSLExampleWorkspace/Frameworks" ]; then
  rm -rf "$WORKDIR/LSLExampleWorkspace/Frameworks/$XCFRAMEWORK_NAME"
  cp -R "$XC_OUT" "$WORKDIR/LSLExampleWorkspace/Frameworks/$XCFRAMEWORK_NAME"
  echo "Updated $WORKDIR/LSLExampleWorkspace/Frameworks/$XCFRAMEWORK_NAME"
fi

# Skip Tuist scaffolding if XCFramework doesn't contain Apple .framework bundles
if ! find "$XC_OUT" -name "*.framework" -print -quit | grep -q .; then
  echo "XCFramework contains libraries (dylib/static) but no .framework bundles; skipping Tuist scaffolding."
  echo "You can integrate the XCFramework manually from: $XC_OUT"
  exit 0
fi

# --- Tuist project scaffolding ---
ROOT="$WORKDIR/$TUIST_PROJECT_NAME"
rm -rf "$ROOT"
mkdir -p "$ROOT/Workspace" "$ROOT/Project" "$ROOT/Frameworks"
cp -R "$XC_OUT" "$ROOT/Frameworks/"

# Minimal Tuist Project.swift (3 targets: iOS app+framework, macOS app+framework, watchOS app+framework)
cat > "$ROOT/Project/Project.swift" <<'SWIFT'
