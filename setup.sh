#!/usr/bin/env bash
set -euo pipefail
IFS=$'\n\t'

# --- Config (edit only if needed) ---
LSL_REPO="https://github.com/sccn/liblsl.git"
WORKDIR="$(pwd)/liblsl-tuist-workspace"
CLONE_DIR="$WORKDIR/third_party/liblsl"
BUILD_DIR_BASE="$WORKDIR/build"
ARCHIVE_DIR="$WORKDIR/archives"
FRAMEWORKS_DIR="$WORKDIR/Frameworks"
XCFRAMEWORK_NAME="liblsl.xcframework"
LSL_TARGET="${LSL_TARGET:-lsl}" # override if upstream CMake target/scheme differs
TUIST_PROJECT_NAME="LSLExampleWorkspace"
TUIST_MIN_VERSION="3.4.0" # optional constraint for tuist generation
# --- end config ---

mkdir -p "$WORKDIR" "$ARCHIVE_DIR" "$FRAMEWORKS_DIR"
echo "Workspace: $WORKDIR"

# Check prerequisites
for cmd in git cmake xcodebuild xcode-select; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Missing required tool: $cmd. Install Xcode (and command line tools) and re-run." >&2
    exit 1
  fi
done

if ! command -v tuist >/dev/null 2>&1; then
  echo "Tuist not found. Installing tuist (system-wide)..." >&2
  curl -Ls https://install.tuist.io | bash || true
  if ! command -v tuist >/dev/null 2>&1; then
    echo "tuist install failed or requires interactive step; please install tuist (https://tuist.io) and re-run." >&2
    exit 1
  fi
fi

# Clone liblsl
rm -rf "$CLONE_DIR"
git clone --depth 1 "$LSL_REPO" "$CLONE_DIR"
cd "$CLONE_DIR"

# Detect project name (for Xcode project generated by cmake)
PROJECT_NAME="$(basename "$CLONE_DIR")"

# Helper: run cmake configure for a build dir (Xcode generator)
cmake_configure() {
  local builddir="$1"
  mkdir -p "$builddir"
  pushd "$builddir" >/dev/null
  cmake -G Xcode "$CLONE_DIR" -DCMAKE_BUILD_TYPE=Release -DLSL_BUILD_STATIC=ON
  popd >/dev/null
}

# Helper: archive for given sdk (macosx / iphoneos / iphonesimulator / watchos / watchsimulator)
archive_for_sdk() {
  local builddir="$1"
  local sdk="$2"
  local archname="$3"   # label for archives
  pushd "$builddir" >/dev/null
  # find the Xcode project generated by cmake
  proj=$(find . -maxdepth 2 -name '*.xcodeproj' | head -n1)
  if [ -z "$proj" ]; then
    echo "Error: Xcode project not found in $builddir" >&2
    exit 1
  fi
  proj_path="$builddir/$proj"
  archive_path="$ARCHIVE_DIR/$archname.xcarchive"
  mkdir -p "$(dirname "$archive_path")"
  # Try archive. If scheme not found, try auto-discovering available schemes.
  set +e
  selected_scheme="$LSL_TARGET"
  xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release -sdk "$sdk" archive -archivePath "$archive_path" SKIP_INSTALL=NO BUILD_LIBRARY_FOR_DISTRIBUTION=YES >/dev/null 2>&1
  rc=$?
  set -e
  if [ $rc -ne 0 ]; then
    echo "xcodebuild archive with scheme $LSL_TARGET failed for sdk $sdk; discovering available schemes..." >&2
    set +e
    mapfile -t schemes < <(xcodebuild -list -project "$proj_path" 2>/dev/null | awk '/Schemes:/{flag=1;next}/Targets:/{flag=0}flag' | sed 's/^ *//;s/ *$//' | sed '/^$/d')
    set -e
    tried_ok=0
    for sch in "${schemes[@]}"; do
      echo "Trying scheme '$sch' for sdk $sdk..." >&2
      set +e
      xcodebuild -project "$proj_path" -scheme "$sch" -configuration Release -sdk "$sdk" archive -archivePath "$archive_path" SKIP_INSTALL=NO BUILD_LIBRARY_FOR_DISTRIBUTION=YES >/dev/null 2>&1
      rc2=$?
      set -e
      if [ $rc2 -eq 0 ]; then
        echo "Archived with scheme '$sch' for $sdk." >&2
        tried_ok=1
        selected_scheme="$sch"
        break
      fi
    done
    if [ "$tried_ok" -ne 1 ]; then
      echo "Failed to archive any scheme for sdk $sdk. Available schemes: ${schemes[*]}" >&2
      echo "Falling back to building the selected scheme to collect libraries." >&2
    fi
  fi
  # If archive exists but is empty (no libs/frameworks), treat as missing
  need_build_fallback=0
  if [ -d "$archive_path" ]; then
    set +e
    find "$archive_path" \( -name 'lib*.a' -o -name 'lib*.dylib' -o -path '*/Products/Library/Frameworks/*.framework' \) -print -quit | grep -q .
    has_artifacts=$?
    set -e
    if [ $has_artifacts -ne 0 ]; then
      echo "Archive at $archive_path contains no libraries/frameworks; falling back to build products." >&2
      need_build_fallback=1
    fi
  else
    need_build_fallback=1
  fi

  if [ $need_build_fallback -eq 1 ]; then
    echo "Performing build for $selected_scheme ($sdk) and using build products." >&2
    
    # Handle iOS simulator: build for both arm64 and x86_64, then create universal binary
    if [ "$sdk" = "iphonesimulator" ]; then
      # Try to build for both architectures (x86_64 for Intel, arm64 for Apple Silicon)
      archs=("x86_64" "arm64")
      lib_paths=()
      
      # Build for each architecture
      for arch in "${archs[@]}"; do
        echo "Building for architecture: $arch" >&2
        set +e
        xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release \
          -sdk "$sdk" -arch "$arch" \
          SKIP_INSTALL=NO BUILD_LIBRARY_FOR_DISTRIBUTION=YES \
          CONFIGURATION_BUILD_DIR="$builddir/Release-$arch" >/dev/null 2>&1
        build_rc=$?
        set -e
        
        if [ $build_rc -eq 0 ]; then
          # Find the built library - try CONFIGURATION_BUILD_DIR first, then search build directory
          lib=$(find "$builddir/Release-$arch" -type f \( -name "liblsl*.dylib" -o -name "liblsl*.a" \) 2>/dev/null | head -n1 || true)
          if [ -z "$lib" ] || [ ! -f "$lib" ]; then
            # Fallback: search in standard build locations
            lib=$(find "$builddir" -type f \( -name "liblsl*.dylib" -o -name "liblsl*.a" \) -path "*/Release*" 2>/dev/null | grep -i "$arch" | head -n1 || true)
          fi
          if [ -n "$lib" ] && [ -f "$lib" ]; then
            lib_paths+=("$lib")
            echo "Found library for $arch: $lib" >&2
          else
            echo "Warning: Library not found for $arch after build" >&2
          fi
        else
          echo "Build for $arch failed (may not be supported on this host)" >&2
        fi
      done
      
      # Create universal binary if we have multiple architectures
      if [ ${#lib_paths[@]} -gt 1 ]; then
        echo "Creating universal binary from ${lib_paths[*]}" >&2
        # Determine library name from first library
        base_lib="${lib_paths[0]}"
        if [[ "$base_lib" == *.dylib ]]; then
          lib_name="liblsl.dylib"
        else
          lib_name="liblsl.a"
        fi
        universal_lib="$builddir/Release/$lib_name"
        mkdir -p "$builddir/Release"
        lipo -create "${lib_paths[@]}" -output "$universal_lib" || {
          echo "lipo failed, using first architecture library" >&2
          cp "${lib_paths[0]}" "$universal_lib"
        }
        echo "$builddir/Release"
      elif [ ${#lib_paths[@]} -eq 1 ]; then
        # Single architecture, copy to Release directory
        echo "Using single architecture library" >&2
        mkdir -p "$builddir/Release"
        cp "${lib_paths[0]}" "$builddir/Release/"
        echo "$builddir/Release"
      else
        echo "Error: No libraries built for iphonesimulator" >&2
        exit 1
      fi
      popd >/dev/null
      return 0
    fi
    
    # For iphoneos, explicitly build for arm64
    if [ "$sdk" = "iphoneos" ]; then
      echo "Building for architecture: arm64 (device)" >&2
      xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release \
        -sdk "$sdk" -arch arm64 \
        SKIP_INSTALL=NO BUILD_LIBRARY_FOR_DISTRIBUTION=YES >/dev/null 2>&1
    else
      # For other SDKs, use default build
      xcodebuild -project "$proj_path" -scheme "$selected_scheme" -configuration Release \
        -sdk "$sdk" build SKIP_INSTALL=NO BUILD_LIBRARY_FOR_DISTRIBUTION=YES >/dev/null 2>&1
    fi
    
    # Discover actual build output location (can vary by SDK)
    # Try multiple possible locations
    lib_path=$(find "$builddir" -type f \( -name "liblsl*.dylib" -o -name "liblsl*.a" \) \
      \( -path "*/Release/*" -o -path "*/Release-*/*" -o -path "*/Release" \) 2>/dev/null | head -n1 || true)
    
    if [ -n "$lib_path" ] && [ -f "$lib_path" ]; then
      output_dir=$(dirname "$lib_path")
      echo "$output_dir"
    else
      # Fallback to standard Release directory (may need to check if build actually succeeded)
      echo "$builddir/Release"
    fi
    popd >/dev/null
    return 0
  fi
  popd >/dev/null
  echo "$archive_path"
}

# Platforms list to attempt (order: device then simulator)
declare -a SDKS=( "macosx" "iphoneos" "iphonesimulator" "watchos" "watchsimulator" )

# Configure and archive per SDK
declare -a BUILD_OUTPUTS=()
declare -A SDK_TO_OUTPUT=()
for sdk in "${SDKS[@]}"; do
  bd="$BUILD_DIR_BASE/$sdk"
  echo "Configuring CMake for $sdk -> $bd"
  cmake_configure "$bd"
  echo "Archiving for sdk $sdk"
  output=$(archive_for_sdk "$bd" "$sdk" "$sdk")
  if [ -n "$output" ] && [ -d "$output" ]; then
    BUILD_OUTPUTS+=("$output")
    SDK_TO_OUTPUT["$sdk"]="$output"
  fi
done

# Collect framework/library + headers from build outputs (archives or build directories)
found_frameworks=()
found_libraries=()
found_headers=()

# Use include directory from source for headers (consistent across all builds)
headers_dir="$CLONE_DIR/include"
if [ -d "$headers_dir" ]; then
  found_headers+=("$headers_dir")
fi

for output in "${BUILD_OUTPUTS[@]}"; do
  # Check if this is an archive (has Products directory) or a build directory
  if [ -d "$output/Products" ]; then
    # This is an xcarchive - look for frameworks in Products
    fw=$(find "$output" -path "*/Products/Library/Frameworks/*.framework" | head -n1 || true)
    if [ -n "$fw" ] && [ -d "$fw" ]; then
      echo "Found framework: $fw"
      found_frameworks+=("$fw")
      continue
    fi
    # Look for libraries in archive Products
    lib=$(find "$output/Products" -name "liblsl*.dylib" | head -n1 || true)
    if [ -z "$lib" ]; then
      lib=$(find "$output/Products" -name "liblsl*.a" | head -n1 || true)
    fi
  else
    # This is a build directory - look for libraries directly
    lib=$(find "$output" -maxdepth 1 -type f \( -name "liblsl*.dylib" -o -name "liblsl*.a" \) | head -n1 || true)
  fi
  
  if [ -n "$lib" ] && [ -f "$lib" ]; then
    echo "Found library: $lib"
    found_libraries+=("$lib")
  fi
done

XC_OUT="$FRAMEWORKS_DIR/$XCFRAMEWORK_NAME"
rm -rf "$XC_OUT"
echo "Creating XCFramework at $XC_OUT"

# Prefer framework -> create xcframework from frameworks
if [ ${#found_frameworks[@]} -gt 0 ]; then
  # Build xcodebuild -create-xcframework with all frameworks
  create_cmd=(xcodebuild -create-xcframework)
  for fw in "${found_frameworks[@]}"; do
    create_cmd+=(-framework "$fw")
  done
  create_cmd+=(-output "$XC_OUT")
  "${create_cmd[@]}"
else
  # Create xcframework from static/dylib + headers (use -library + -headers for each slice)
  if [ ${#found_libraries[@]} -eq 0 ]; then
    echo "No frameworks or libraries found in build outputs; aborting." >&2
    exit 1
  fi
  create_cmd=(xcodebuild -create-xcframework)
  # Use the shared headers directory for all libraries (from source)
  hdrdir="${found_headers[0]:-$CLONE_DIR/include}"
  if [ ! -d "$hdrdir" ]; then
    echo "Warning: Headers directory not found at $hdrdir, libraries may be incomplete" >&2
  fi
  for lib in "${found_libraries[@]}"; do
    create_cmd+=(-library "$lib" -headers "$hdrdir")
  done
  create_cmd+=(-output "$XC_OUT")
  "${create_cmd[@]}"
fi

echo "XCFramework created: $XC_OUT"

# Skip Tuist scaffolding if XCFramework doesn't contain Apple .framework bundles
if ! find "$XC_OUT" -name "*.framework" -print -quit | grep -q .; then
  echo "XCFramework contains libraries (dylib/static) but no .framework bundles; skipping Tuist scaffolding."
  echo "You can integrate the XCFramework manually from: $XC_OUT"
  exit 0
fi

# --- Tuist project scaffolding ---
ROOT="$WORKDIR/$TUIST_PROJECT_NAME"
rm -rf "$ROOT"
mkdir -p "$ROOT/Workspace" "$ROOT/Project" "$ROOT/Frameworks"
cp -R "$XC_OUT" "$ROOT/Frameworks/"

# Minimal Tuist Project.swift (3 targets: iOS app+framework, macOS app+framework, watchOS app+framework)
cat > "$ROOT/Project/Project.swift" <<'SWIFT'
import ProjectDescription

let libDep: TargetDependency = .xcframework(path: .relativeToManifest("Frameworks/liblsl.xcframework"))

let wrapper_iOS: Target = .target(
  name: "LSLWrapper-iOS",
  destinations: .iOS,
  product: .framework,
  bundleId: "io.example.LSLWrapper-iOS",
  infoPlist: .default,
  sources: ["LSLWrapper/Sources/**"],
  dependencies: [libDep]
)

let app_iOS: Target = .target(
  name: "LSLApp-iOS",
  destinations: .iOS,
  product: .app,
  bundleId: "io.example.LSLApp-iOS",
  infoPlist: .default,
  sources: ["Apps/IOSApp/Sources/**"],
  dependencies: [.target(name: "LSLWrapper-iOS")]
)

let wrapper_mac: Target = .target(
  name: "LSLWrapper-macOS",
  destinations: .macOS,
  product: .framework,
  bundleId: "io.example.LSLWrapper-macOS",
  infoPlist: .default,
  sources: ["LSLWrapper/Sources/**"],
  dependencies: [libDep]
)

let app_mac: Target = .target(
  name: "LSLApp-macOS",
  destinations: .macOS,
  product: .app,
  bundleId: "io.example.LSLApp-macOS",
  infoPlist: .default,
  sources: ["Apps/MacApp/Sources/**"],
  dependencies: [.target(name: "LSLWrapper-macOS")]
)

let wrapper_watch: Target = .target(
  name: "LSLWrapper-watchOS",
  destinations: .watchOS,
  product: .framework,
  bundleId: "io.example.LSLWrapper-watchOS",
  infoPlist: .default,
  sources: ["LSLWrapper/Sources/**"],
  dependencies: [libDep]
)

let app_watch: Target = .target(
  name: "LSLApp-watchOS",
  destinations: .watchOS,
  product: .app,
  bundleId: "io.example.LSLApp-watchOS",
  infoPlist: .default,
  sources: ["Apps/WatchApp/Sources/**"],
  dependencies: [.target(name: "LSLWrapper-watchOS")]
)

let project = Project(
  name: "LSLExample",
  targets: [wrapper_iOS, app_iOS, wrapper_mac, app_mac, wrapper_watch, app_watch]
)
SWIFT

# Minimal wrapper source (Objective-C++ bridging)
mkdir -p "$ROOT/Project/LSLWrapper/Sources"
cat > "$ROOT/Project/LSLWrapper/Sources/LSLWrapper.h" <<'H'
#import <Foundation/Foundation.h>
@interface LSLWrapper : NSObject
+ (nullable NSString*)lslVersionC;
@end
H
cat > "$ROOT/Project/LSLWrapper/Sources/LSLWrapper.mm" <<'MM'
#import "LSLWrapper.h"
extern "C" {
#include <lsl_c.h>
}
@implementation LSLWrapper
+ (NSString*)lslVersionC {
  const char* v = lsl_get_library_version();
  if(!v) return nil;
  return [NSString stringWithUTF8String:v];
}
@end
MM

# Minimal app skeletons
mkdir -p "$ROOT/Project/Apps/IOSApp/Sources" "$ROOT/Project/Apps/MacApp/Sources" "$ROOT/Project/Apps/WatchApp/Sources"
cat > "$ROOT/Project/Apps/IOSApp/Sources/main.swift" <<'SWIFT'
import UIKit
@UIApplicationMain
class AppDelegate: UIResponder, UIApplicationDelegate {
  var window: UIWindow?
  func application(_ application: UIApplication,didFinishLaunchingWithOptions launchOptions:[UIApplication.LaunchOptionsKey:Any]?=nil)->Bool{
    print("LSL wrapper version:", LSLWrapper.lslVersionC() ?? "nil")
    return true
  }
}
SWIFT

cat > "$ROOT/Project/Apps/MacApp/Sources/main.swift" <<'SWIFT'
import Cocoa
@NSApplicationMain
class AppDelegate: NSObject, NSApplicationDelegate {
  func applicationDidFinishLaunching(_ aNotification: Notification) {
    print("LSL wrapper version:", LSLWrapper.lslVersionC() ?? "nil")
  }
}
SWIFT

cat > "$ROOT/Project/Apps/WatchApp/Sources/main.swift" <<'SWIFT'
import WatchKit
class ExtensionDelegate: NSObject, WKExtensionDelegate {}
WKExtension.shared().delegate = ExtensionDelegate()
print("LSL wrapper version:", LSLWrapper.lslVersionC() ?? "nil")
SWIFT

# Copy Project.swift to root of Tuist project (tuist expects Project.swift at root)
mv "$ROOT/Project/Project.swift" "$ROOT/Project.swift"
mv "$ROOT/Project/LSLWrapper" "$ROOT/LSLWrapper"
mv "$ROOT/Project/Apps" "$ROOT/Apps"

# Move xcframework up to root Frameworks
# Frameworks already placed in $ROOT/Frameworks by copy above

# Run tuist generate
pushd "$ROOT" >/dev/null
echo "Generating Tuist workspace..."
tuist generate
popd >/dev/null

echo "Done. Workspace at: $ROOT"
echo "Open the generated Xcode workspace (Workspace/LSLExample.xcworkspace) or open with 'tuist open' from $ROOT"
s
